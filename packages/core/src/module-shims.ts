// Typing what cells import: `npm:zod@4`, `jsr:@std/expect`, `node:path`,
// bare names from a deno.json import map, remote URLs.
//
// TypeScript can't resolve those specifiers, but it will take an ambient
// module declaration for each one that re-exports the real module:
//
//   declare module "npm:zod@4" { export * from "zod"; export { default } from "zod"; }
//
// `zod` then resolves through a node_modules folder next to the declaration
// file (which links to Deno's npm cache), and remote modules through files
// copied next to it. A specifier whose types haven't arrived yet gets a
// shorthand declaration (`declare module "npm:zod@4";`), which types every
// import from it as `any` instead of reporting "Cannot find module".
//
// Browser-safe: the web app's worker receives the same declaration text.

export interface Specifier {
  scheme: "npm" | "jsr" | "node" | "remote" | "file" | "data" | "bare";
  /** npm/jsr: the package name, scope included; node: the built-in's name. */
  name?: string;
  /** npm/jsr: the version or range written after the name. */
  version?: string;
  /** npm/jsr: what follows the package name, e.g. `v4` in `npm:zod@4/v4`. */
  subpath?: string;
}

const PACKAGE = /^(npm|jsr):\/?(@[^/@]+\/[^/@]+|[^/@]+)(?:@([^/]*))?(?:\/(.*))?$/;

export function parseSpecifier(spec: string): Specifier {
  const m = PACKAGE.exec(spec);
  if (m) return { scheme: m[1] as "npm" | "jsr", name: m[2], ...(m[3] ? { version: m[3] } : {}), ...(m[4] ? { subpath: m[4] } : {}) };
  if (spec.startsWith("node:")) return { scheme: "node", name: spec.slice(5) };
  if (/^https?:\/\//.test(spec)) return { scheme: "remote" };
  if (/^(\.\.?\/|\/|file:)/.test(spec) || /^[A-Za-z]:[\\/]/.test(spec)) return { scheme: "file" };
  if (/^(data|blob):/.test(spec)) return { scheme: "data" };
  return { scheme: "bare" };
}

/** Specifiers TypeScript can't resolve by itself and Deno can. */
export const needsDeno = (spec: string) => parseSpecifier(spec).scheme !== "file";

export interface ModuleShim {
  specifier: string;
  /** What the declaration re-exports: a bare package name (+ subpath) found in node_modules, or a path relative to the declaration file. Absent: shorthand (`any`). */
  from?: string;
}

/** The file holding the declarations, at the root of a types folder. */
export const SHIMS_FILE = "modules.d.ts";

/** Declaration text for a set of specifiers. `nodeTypes` adds `@types/node` (which declares the `node:` built-ins). */
export function moduleShims(shims: ModuleShim[], opts: { nodeTypes?: boolean } = {}): string {
  const lines = ["// Generated by Polyglot Tutor: types for what the notebook's cells import."];
  if (opts.nodeTypes) lines.push('/// <reference types="node" />');
  const seen = new Set<string>();
  for (const s of shims) {
    if (seen.has(s.specifier)) continue;
    seen.add(s.specifier);
    const spec = JSON.stringify(s.specifier);
    if (s.from === undefined) lines.push(`declare module ${spec};`);
    else {
      const from = JSON.stringify(s.from);
      lines.push(`declare module ${spec} { export * from ${from}; export { default } from ${from}; }`);
    }
  }
  return lines.join("\n") + "\n";
}

import assert from "node:assert/strict";
import { test } from "node:test";
import { moduleShims, needsDeno, parseSpecifier } from "../src/module-shims.ts";

test("parseSpecifier reads npm:/jsr: names, versions and subpaths, and tells the other kinds apart", () => {
  assert.deepEqual(parseSpecifier("npm:zod@4"), { scheme: "npm", name: "zod", version: "4" });
  assert.deepEqual(parseSpecifier("npm:/zod@4.6.7/v4"), { scheme: "npm", name: "zod", version: "4.6.7", subpath: "v4" });
  assert.deepEqual(parseSpecifier("npm:@anthropic-ai/sdk@^1/resources/messages"), { scheme: "npm", name: "@anthropic-ai/sdk", version: "^1", subpath: "resources/messages" });
  assert.deepEqual(parseSpecifier("npm:zod"), { scheme: "npm", name: "zod" });
  assert.deepEqual(parseSpecifier("jsr:@std/expect"), { scheme: "jsr", name: "@std/expect" });
  assert.deepEqual(parseSpecifier("node:fs/promises"), { scheme: "node", name: "fs/promises" });
  assert.deepEqual(parseSpecifier("https://esm.sh/nanoid@5"), { scheme: "remote" });
  for (const s of ["./a.ts", "../b", "/abs/c.ts", "file:///x.ts", "C:\\x\\y.ts"]) assert.deepEqual(parseSpecifier(s), { scheme: "file" }, s);
  assert.deepEqual(parseSpecifier("data:text/javascript,1"), { scheme: "data" });
  assert.deepEqual(parseSpecifier("zod"), { scheme: "bare" });
});

test("needsDeno: everything but a path", () => {
  assert.equal(needsDeno("./lib/x.ts"), false);
  for (const s of ["npm:zod@4", "jsr:@std/expect", "node:path", "zod", "https://esm.sh/x"]) assert.equal(needsDeno(s), true, s);
});

test("moduleShims declares each specifier once: re-exporting its real module, or shorthand when its types are pending", () => {
  const text = moduleShims([
    { specifier: "npm:zod@4", from: "zod" },
    { specifier: "jsr:@std/expect", from: "./remote/jsr.io/@std/expect/1.0.20/mod.ts" },
    { specifier: "npm:pending@1" },
    { specifier: "npm:zod@4", from: "zod/v4" }, // a repeat is ignored
  ]);
  assert.equal(
    text,
    `// Generated by Polyglot Tutor: types for what the notebook's cells import.
declare module "npm:zod@4" { export * from "zod"; export { default } from "zod"; }
declare module "jsr:@std/expect" { export * from "./remote/jsr.io/@std/expect/1.0.20/mod.ts"; export { default } from "./remote/jsr.io/@std/expect/1.0.20/mod.ts"; }
declare module "npm:pending@1";
`,
  );
});

test("moduleShims references @types/node when asked, so node: built-ins are declared", () => {
  assert.match(moduleShims([], { nodeTypes: true }), /^\/\/.*\n\/\/\/ <reference types="node" \/>\n$/);
  assert.doesNotMatch(moduleShims([]), /reference types/);
});
